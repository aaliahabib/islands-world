def text_width(text: str, size: float) -> float:
    """Width in pixels that `draw_text` will occupy, for centering."""
    if not text:
        return 0.0
    unit = size / GLYPH_H
    return (len(text) * ADVANCE - (ADVANCE - GLYPH_W)) * unit


def draw_text(
    surface: pygame.Surface,
    text: str,
    pos: tuple[float, float],
    size: float = 24,
    color: tuple[int, int, int] = (255, 255, 255),
    width: int = 2,
    center: bool = False,
) -> None:
    """Draw `text` as vector strokes. `pos` is the top-left, or the top-centre
    when `center=True`."""
    text = str(text).upper()
    unit = size / GLYPH_H
    x, y = pos
    if center:
        x -= text_width(text, size) / 2

    for char in text:
        strokes = GLYPHS.get(char)
        if strokes is None:
            strokes = GLYPHS["?"]
        for stroke in strokes:
            points = [(x + px * unit, y + py * unit) for px, py in stroke]
            if len(points) >= 2:
                pygame.draw.lines(surface, color, False, points, width)
        x += ADVANCE * unit
